test('review shows prior debts and reservations, then approves, edits safely and pays once with optional proof', async () => {
  const user = await prisma.user.create({ data: { acccode: 'review-admin', password: 'test', role: 'ADMIN', level: 0 } })
  const borrower = await prisma.borrower.create({ data: { nickname: 'review', firstName: 'Test', lastName: 'Review', phone: '', approvedLimit: 1000 } })
  const lender = await prisma.lender.create({ data: { nickname: 'lender' } })
  await prisma.paymentChannel.create({ data: { code: 'BANKING', nameTh: 'ธนาคาร' } })
  await prisma.financialCategory.create({ data: { code: 'LOAN_DISBURSEMENT', nameTh: 'จ่ายเงินกู้', direction: 'OUT', group: 'LOAN' } })
  const base = { borrowerId: borrower.id, lenderId: lender.id, borrowerCode: 'BR-TEST', borrowerName: 'Test Review', lenderName: 'Lender', documentChoice: 'NONE', interestMethod: 'INTEREST_WITH_PRINCIPAL', interestPercent: 0, principalSatang: 100000, interestSatang: 0, netSatang: 100000, repaymentSatang: 100000, createdBy: user.id, scheduledDisbursementDate: '2026-10-23', repaymentDueDate: '2027-01-01' }
  const existing = await prisma.loanContract.create({ data: { ...base, requestKey: randomUUID(), status: 'PAID', paidAt: new Date('2026-01-01T00:00:00+07:00') } })
  await prisma.ledgerEntry.createMany({ data: [
    { requestKey: randomUUID(), contractId: existing.id, kind: 'DISBURSEMENT', direction: 'OUT', categoryCode: 'LOAN_DISBURSEMENT', categoryName: 'จ่ายเงินกู้', amountSatang: 100000, occurredOn: '2026-01-01', channelCode: 'BANKING', channelName: 'ธนาคาร', createdBy: user.id },
    { requestKey: randomUUID(), contractId: existing.id, kind: 'REPAYMENT', direction: 'IN', categoryCode: 'CONTRACT_REPAYMENT', categoryName: 'รับชำระ', amountSatang: 20000, occurredOn: '2026-01-02', channelCode: 'BANKING', channelName: 'ธนาคาร', createdBy: user.id },
  ] })
  await prisma.loanContract.create({ data: { ...base, requestKey: randomUUID(), principalSatang: 50000, netSatang: 50000, repaymentSatang: 50000 } })
  const target = await prisma.loanContract.create({ data: { ...base, requestKey: randomUUID(), limitApprovalRequired: true } })
  let review = await getPendingContractReview(target.id)
  assert.equal(review.outstandingContracts.length, 1)
  assert.equal(review.outstandingContracts[0].id, existing.id)
  assert.equal(review.outstandingSatang, 80000)
  assert.equal(review.reservedOtherSatang, 50000)
  assert.equal(review.availableBeforeSatang, -30000)
  assert.equal(review.availableAfterSatang, -130000)
  assert.ok((await approvePendingContract(target.id, '')).error, 'approval requires viewing the summary')
  await prisma.borrower.update({ where: { id: borrower.id }, data: { approvedLimit: 1200 } })
  assert.match((await approvePendingContract(target.id, review.reviewToken)).error!, /เปลี่ยนแปลง/)
  review = await getPendingContractReview(target.id)
  assert.ok((await approvePendingContract(target.id, review.reviewToken)).success)
  assert.equal(await prisma.ledgerEntry.count({ where: { contractId: target.id } }), 0, 'approval is not a payment')
  review = await getPendingContractReview(target.id)
  const stalePayoutToken = review.reviewToken
  const edit = { id: target.id, reviewToken: review.reviewToken, principal: '1000', scheduledDisbursementDate: '2026-10-24', repaymentDueDate: '2027-02-01', collateralDescription: '', reason: 'เลื่อนวันนัดจ่าย', confirmResetSignatures: false }
  assert.ok((await editPendingContract(edit)).success)
  assert.match((await editPendingContract(edit)).error!, /เปลี่ยนแปลง/)
  let stored = await prisma.loanContract.findUniqueOrThrow({ where: { id: target.id } })
  assert.equal(stored.limitApprovalRequired, false, 'date-only changes preserve approval')
  assert.equal(stored.repaymentDueDate, '2027-02-01')
  const pay = { requestKey: randomUUID(), contractId: target.id, kind: 'DISBURSEMENT' as const, direction: 'OUT', categoryCode: '', amount: '1000', occurredOn: bangkokToday(), channelCode: 'BANKING', reference: 'REVIEW-PAYMENT', note: '', contractReviewToken: stalePayoutToken }
  const stalePayment = await saveLedger(pay)
  assert.match(stalePayment.error!, /เปลี่ยนแปลง/)
  assert.equal('code' in stalePayment && stalePayment.code, 'STALE_CONTRACT_REVIEW')
  assert.equal(await prisma.ledgerEntry.count({ where: { contractId: target.id } }), 0)
  review = await getPendingContractReview(target.id)
  assert.ok((await editPendingContract({ ...edit, reviewToken: review.reviewToken, principal: '1500', reason: 'เพิ่มยอดขอจอง' })).success)
  stored = await prisma.loanContract.findUniqueOrThrow({ where: { id: target.id } })
  assert.equal(stored.limitApprovalRequired, true, 'increased over-limit principal must be approved again')
  assert.ok((await saveLedger({ ...pay, amount: '1500', contractReviewToken: undefined })).error)
  review = await getPendingContractReview(target.id)
  assert.ok((await approvePendingContract(target.id, review.reviewToken)).success)
  await prisma.loanContract.update({ where: { id: target.id }, data: { signingMethod: 'E_SIGNATURE', documentChoice: 'CREATE', documentPackage: 'LOAN', witnessCount: 0, borrowerSignedAt: new Date(), lenderSignedAt: new Date(), borrowerSignatureData: 'old-signature' } })
  review = await getPendingContractReview(target.id)
  assert.ok(review.hasSignatures)
  assert.match((await editPendingContract({ ...edit, reviewToken: review.reviewToken, principal: '1500', scheduledDisbursementDate: '2026-10-25', reason: 'แก้ฉบับที่ลงนามแล้ว' })).error!, /ลงนามใหม่/)
  assert.ok((await editPendingContract({ ...edit, reviewToken: review.reviewToken, principal: '1500', scheduledDisbursementDate: '2026-10-25', reason: 'แก้ฉบับที่ลงนามแล้ว', confirmResetSignatures: true })).success)
  stored = await prisma.loanContract.findUniqueOrThrow({ where: { id: target.id } })
  assert.equal(stored.borrowerSignedAt, null)
  const revision = await prisma.contractRevision.findFirstOrThrow({ where: { contractId: target.id, kind: 'EDIT' }, orderBy: { id: 'desc' } })
  assert.ok(revision.beforeJson.includes('old-signature'), 'old signature is archived, not lost')
  review = await getPendingContractReview(target.id)
  assert.ok((await saveLedger({ ...pay, amount: '1500', contractReviewToken: review.reviewToken })).error, 'edited e-contract must be signed again')
  await prisma.loanContract.update({ where: { id: target.id }, data: { borrowerSignedAt: new Date(), lenderSignedAt: new Date() } })
  review = await getPendingContractReview(target.id)
  const finalPay = { ...pay, amount: '1500', contractReviewToken: review.reviewToken }
  assert.ok((await saveLedger(finalPay)).success, 'proof is optional')
  assert.ok((await saveLedger(finalPay)).success, 'retry does not pay twice')
  assert.equal(await prisma.ledgerEntry.count({ where: { contractId: target.id, kind: 'DISBURSEMENT', voidedAt: null } }), 1)
  assert.ok((await editPendingContract({ ...edit, reviewToken: review.reviewToken })).error, 'paid contracts are locked')
  const unpaid = await prisma.loanContract.findFirstOrThrow({ where: { status: 'WAITING_PAYMENT' } })
  await prisma.user.update({ where: { id: user.id }, data: { role: 'REVIEWER' } })
  await assert.rejects(getPendingContractReview(unpaid.id), /ไม่มีสิทธิ์/)
  assert.ok((await approvePendingContract(unpaid.id, 'anything')).error)
})

test('rejection requires an admin, current review and reason; releases reservation and retains audit without paying', async () => {
  const admin = await prisma.user.create({ data: { acccode: 'reject-admin', password: 'test', role: 'ADMIN', level: -1 } })
  const borrower = await prisma.borrower.create({ data: { nickname: 'reject-review', firstName: 'Reject', lastName: 'Test', phone: '', approvedLimit: 500 } })
  const lender = await prisma.lender.findFirstOrThrow()
  const base = { borrowerId: borrower.id, lenderId: lender.id, borrowerCode: 'BR-REJECT', borrowerName: 'Reject Test', lenderName: 'Lender', documentChoice: 'NONE', interestMethod: 'INTEREST_WITH_PRINCIPAL', interestPercent: 0, principalSatang: 100000, interestSatang: 0, netSatang: 100000, repaymentSatang: 100000, createdBy: admin.id, scheduledDisbursementDate: '2026-10-24', repaymentDueDate: '2026-11-24', limitApprovalRequired: true }
  const candidate = await prisma.loanContract.create({ data: { ...base, requestKey: randomUUID() } })
  let review = await getPendingContractReview(candidate.id)
  assert.ok((await rejectPendingContract(candidate.id, review.reviewToken, '  ')).error)
  assert.ok((await rejectPendingContract(candidate.id, review.reviewToken, 'x'.repeat(501))).error)
  await prisma.user.update({ where: { id: admin.id }, data: { role: 'LOAN_OFFICER' } })
  assert.ok((await rejectPendingContract(candidate.id, review.reviewToken, 'เอกสารไม่ครบ')).error)
  assert.equal((await prisma.loanContract.findUniqueOrThrow({ where: { id: candidate.id } })).status, 'WAITING_PAYMENT')
  await prisma.user.update({ where: { id: admin.id }, data: { role: 'ADMIN' } })
  await prisma.loanContract.update({ where: { id: candidate.id }, data: { collateralDescription: 'updated while reviewing' } })
  assert.match((await rejectPendingContract(candidate.id, review.reviewToken, 'เอกสารไม่ครบ')).error!, /เปลี่ยนแปลง/)
  review = await getPendingContractReview(candidate.id)
  const before = await prisma.loanContract.findMany({ where: { borrowerId: borrower.id }, include: { ledgerEntries: true } })
  assert.equal(borrowerPosition(before, 0).reservedLimit, 1000)
  assert.ok((await rejectPendingContract(candidate.id, review.reviewToken, '  มียอดคงค้างสูง ไม่อนุมัติเพิ่ม  ')).success)
  const rejected = await prisma.loanContract.findUniqueOrThrow({ where: { id: candidate.id }, include: { ledgerEntries: true } })
  assert.equal(rejected.status, 'REJECTED')
  assert.equal(rejected.limitApprovalRequired, false)
  assert.equal(rejected.paidAt, null)
  assert.equal(rejected.ledgerEntries.length, 0)
  assert.equal(borrowerPosition([rejected], 0).reservedLimit, 0)
  assert.equal(await prisma.loanContract.count({ where: { id: candidate.id, status: 'WAITING_PAYMENT' } }), 0)
  const history = await prisma.contractRevision.findFirstOrThrow({ where: { contractId: candidate.id, kind: 'REJECTION' } })
  assert.equal(history.reason, 'มียอดคงค้างสูง ไม่อนุมัติเพิ่ม')
  assert.equal(history.createdBy, admin.id)
  assert.ok(history.createdAt)
  assert.equal((await listContracts()).find(c => c.id === candidate.id)?.revisions[0].reason, history.reason)
  assert.ok((await rejectPendingContract(candidate.id, review.reviewToken, 'duplicate')).error)
  assert.equal(await prisma.contractRevision.count({ where: { contractId: candidate.id, kind: 'REJECTION' } }), 1)
  assert.ok((await approvePendingContract(candidate.id, review.reviewToken)).error)
  const another = await prisma.loanContract.create({ data: { ...base, requestKey: randomUUID() } })
  review = await getPendingContractReview(another.id)
  assert.ok((await approvePendingContract(another.id, review.reviewToken)).success)
  review = await getPendingContractReview(another.id)
  assert.match((await rejectPendingContract(another.id, review.reviewToken, 'too late')).error!, /อนุมัติแล้ว/)
  await prisma.loanContract.update({ where: { id: another.id }, data: { status: 'PAID', paidAt: new Date() } })
  assert.ok((await rejectPendingContract(another.id, review.reviewToken, 'paid')).error)
})

test('pending edit switches interest collection without changing principal, preserves history and locks paid contracts', async () => {
  const user = await prisma.user.create({ data: { acccode: 'method-admin', password: 'test', role: 'ADMIN', level: -2 } })
  const borrower = await prisma.borrower.create({ data: { nickname: 'method', firstName: 'Method', lastName: 'Test', phone: '', approvedLimit: 10000 } })
  const lender = await prisma.lender.findFirstOrThrow()
  const contract = await prisma.loanContract.create({ data: { borrowerId: borrower.id, lenderId: lender.id, borrowerCode: 'BR-METHOD', borrowerName: 'Method Test', lenderName: 'Lender', documentChoice: 'NONE', interestMethod: 'INTEREST_UPFRONT', interestPercent: 0, internalInterestPercent: 10, principalSatang: 200000, interestSatang: 20000, netSatang: 180000, repaymentSatang: 200000, createdBy: user.id, requestKey: randomUUID(), scheduledDisbursementDate: '2026-10-31', repaymentDueDate: '2026-11-30' } })
  let review = await getPendingContractReview(contract.id)
  const input = { id: contract.id, reviewToken: review.reviewToken, principal: '2000', interestMethod: 'INVALID', scheduledDisbursementDate: '2026-10-31', repaymentDueDate: '2026-11-30', collateralDescription: '', reason: 'เปลี่ยนเป็นชำระดอกพร้อมเงินต้น', confirmResetSignatures: false }
  assert.ok((await editPendingContract(input)).error)
  assert.ok((await editPendingContract({ ...input, interestMethod: 'INTEREST_WITH_PRINCIPAL' })).success)
  let stored = await prisma.loanContract.findUniqueOrThrow({ where: { id: contract.id } })
  assert.equal(stored.interestMethod, 'INTEREST_WITH_PRINCIPAL')
  assert.equal(stored.principalSatang, 200000)
  assert.equal(stored.interestSatang, 20000)
  assert.equal(stored.netSatang, 200000)
  assert.equal(stored.repaymentSatang, 220000)
  assert.equal(stored.limitApprovalRequired, false)
  assert.equal(await prisma.ledgerEntry.count({ where: { contractId: contract.id } }), 0)
  const revision = await prisma.contractRevision.findFirstOrThrow({ where: { contractId: contract.id, kind: 'EDIT' } })
  assert.equal(JSON.parse(revision.beforeJson).interestMethod, 'INTEREST_UPFRONT')
  assert.equal(JSON.parse(revision.afterJson).interestMethod, 'INTEREST_WITH_PRINCIPAL')
  assert.ok((await editPendingContract({ ...input, interestMethod: 'INTEREST_UPFRONT' })).error, 'old payout review becomes stale')
  review = await getPendingContractReview(contract.id)
  assert.ok((await editPendingContract({ ...input, reviewToken: review.reviewToken, interestMethod: 'INTEREST_UPFRONT' })).success)
  stored = await prisma.loanContract.findUniqueOrThrow({ where: { id: contract.id } })
  assert.equal(stored.netSatang, 180000)
  assert.equal(stored.repaymentSatang, 200000)
  review = await getPendingContractReview(contract.id)
  await prisma.interestRate.createMany({ data: [{ code: 'MASTER20', percent: 20 }, { code: 'MASTER0', percent: 0 }, { code: 'INACTIVE', percent: 30, isActive: false }] })
  review = await getPendingContractReview(contract.id)
  assert.deepEqual(review.interestRates.map(item => item.percent), [0, 20])
  await prisma.interestRate.update({ where: { code: 'MASTER20' }, data: { sortOrder: -1 } })
  const reorderedReview = await getPendingContractReview(contract.id)
  assert.equal(reorderedReview.reviewToken, review.reviewToken, 'master option ordering does not change contract confirmation')
  await prisma.interestRate.update({ where: { code: 'MASTER20' }, data: { percent: 21 } })
  assert.equal((await getPendingContractReview(contract.id)).reviewToken, review.reviewToken, 'unselected master options do not change the existing contract')
  await prisma.interestRate.update({ where: { code: 'MASTER20' }, data: { percent: 20 } })
  for (const invalid of ['', 'MISSING', 'INACTIVE']) assert.ok((await editPendingContract({ ...input, reviewToken: review.reviewToken, interestMethod: 'INTEREST_UPFRONT', internalRateCode: invalid })).error)
  assert.ok((await editPendingContract({ ...input, reviewToken: review.reviewToken, interestMethod: 'INTEREST_UPFRONT', internalRateCode: 'MASTER20' })).success)
  stored = await prisma.loanContract.findUniqueOrThrow({ where: { id: contract.id } })
  assert.equal(stored.internalInterestPercent, 20)
  assert.equal(stored.interestSatang, 40000)
  assert.equal(stored.netSatang, 160000)
  assert.equal(stored.repaymentSatang, 200000)
  const rateAudit = await prisma.contractRevision.findFirstOrThrow({ where: { contractId: contract.id }, orderBy: { id: 'desc' } })
  assert.equal(JSON.parse(rateAudit.afterJson).internalInterestPercent, 20)
  review = await getPendingContractReview(contract.id)
  assert.ok((await editPendingContract({ ...input, reviewToken: review.reviewToken, interestMethod: 'INTEREST_WITH_PRINCIPAL', internalRateCode: 'MASTER0' })).success)
  stored = await prisma.loanContract.findUniqueOrThrow({ where: { id: contract.id } })
  assert.equal(stored.interestSatang, 0)
  assert.equal(stored.netSatang, 200000)
  assert.equal(stored.repaymentSatang, 200000)
  review = await getPendingContractReview(contract.id)
  await prisma.loanContract.update({ where: { id: contract.id }, data: { status: 'PAID', paidAt: new Date() } })
  assert.ok((await editPendingContract({ ...input, reviewToken: review.reviewToken, interestMethod: 'INTEREST_WITH_PRINCIPAL' })).error)
})


test('cancel an approved unpaid contract with reason, audit and released credit; disallow unauthorized or funded cancellation', async () => {
  const admin = await prisma.user.create({ data: { acccode: 'cancel-admin', password: 'test', role: 'ADMIN', level: -3 } })
  const borrower = await prisma.borrower.create({ data: { nickname: 'cancel', firstName: 'Cancel', lastName: 'Test', phone: '', approvedLimit: 5000 } })
  const lender = await prisma.lender.findFirstOrThrow()
  const candidate = await prisma.loanContract.create({ data: { borrowerId: borrower.id, lenderId: lender.id, borrowerCode: 'BR-CANCEL', borrowerName: 'Cancel Test', lenderName: 'Lender', documentChoice: 'NONE', interestMethod: 'INTEREST_UPFRONT', interestPercent: 10, principalSatang: 300000, interestSatang: 30000, netSatang: 270000, repaymentSatang: 300000, createdBy: admin.id, requestKey: randomUUID(), limitApprovedAt: new Date(), limitApprovedBy: admin.id } })
  let review = await getPendingContractReview(candidate.id)
  assert.ok((await cancelPendingContract(candidate.id, review.reviewToken, '')).error)
  assert.ok((await cancelPendingContract(candidate.id, review.reviewToken, 'x'.repeat(501))).error)
  await prisma.user.update({ where: { id: admin.id }, data: { role: 'LOAN_OFFICER' } })
  assert.ok((await cancelPendingContract(candidate.id, review.reviewToken, 'ผู้กู้ยกเลิก')).error)
  await prisma.user.update({ where: { id: admin.id }, data: { role: 'ADMIN' } })
  await prisma.loanContract.update({ where: { id: candidate.id }, data: { collateralDescription: 'changed' } })
  assert.ok((await cancelPendingContract(candidate.id, review.reviewToken, 'ผู้กู้ยกเลิก')).error)
  review = await getPendingContractReview(candidate.id)
  assert.ok((await cancelPendingContract(candidate.id, review.reviewToken, '  ผู้กู้ไม่ต้องการรับเงินแล้ว  ')).success)
  const cancelled = await prisma.loanContract.findUniqueOrThrow({ where: { id: candidate.id }, include: { ledgerEntries: true } })
  assert.equal(cancelled.status, 'CANCELLED')
  assert.equal(cancelled.paidAt, null)
  assert.equal(cancelled.ledgerEntries.length, 0)
  assert.equal(borrowerPosition([cancelled], 0).reservedLimit, 0)
  assert.equal(cancelled.limitApprovedBy, admin.id, 'preserve previous approval history')
  const audit = await prisma.contractRevision.findFirstOrThrow({ where: { contractId: candidate.id, kind: 'CANCELLATION' } })
  assert.equal(audit.reason, 'ผู้กู้ไม่ต้องการรับเงินแล้ว')
  assert.equal(audit.createdBy, admin.id)
  const listed = (await listContracts()).find(row => row.id === candidate.id)!
  assert.equal(listed.revisions[0].reason, audit.reason)
  assert.ok((await cancelPendingContract(candidate.id, review.reviewToken, 'repeat')).error)
  assert.ok((await approvePendingContract(candidate.id, review.reviewToken)).error)
  assert.ok((await saveLedger({ requestKey: randomUUID(), contractId: candidate.id, kind: 'DISBURSEMENT', direction: 'OUT', categoryCode: '', amount: '2700', occurredOn: bangkokToday(), channelCode: 'BANKING', reference: 'CANCELLED-PAY', note: '', contractReviewToken: review.reviewToken })).error, 'cancelled contracts cannot be paid')
  assert.equal(await prisma.contractRevision.count({ where: { contractId: candidate.id, kind: 'CANCELLATION' } }), 1)
  const funded = await prisma.loanContract.findFirstOrThrow({ where: { status: 'PAID' } })
  assert.ok((await cancelPendingContract(funded.id, review.reviewToken, 'cannot cancel paid')).error)
  const awaiting = await prisma.loanContract.create({ data: { borrowerId: borrower.id, lenderId: lender.id, borrowerCode: 'BR-CANCEL', borrowerName: 'Cancel Test', lenderName: 'Lender', documentChoice: 'NONE', interestMethod: 'INTEREST_UPFRONT', interestPercent: 10, principalSatang: 300000, interestSatang: 30000, netSatang: 270000, repaymentSatang: 300000, createdBy: admin.id, requestKey: randomUUID() } })
  review = await getPendingContractReview(awaiting.id)
  await prisma.ledgerEntry.create({ data: { requestKey: randomUUID(), contractId: awaiting.id, kind: 'DISBURSEMENT', direction: 'OUT', categoryCode: 'LOAN_DISBURSEMENT', categoryName: 'จ่ายเงินกู้', amountSatang: 270000, occurredOn: '2026-10-31', channelCode: 'BANKING', channelName: 'ธนาคาร', createdBy: admin.id } })
  assert.ok((await cancelPendingContract(awaiting.id, review.reviewToken, 'raced payment')).error)
  assert.equal((await prisma.loanContract.findUniqueOrThrow({ where: { id: awaiting.id } })).status, 'WAITING_PAYMENT')
})
